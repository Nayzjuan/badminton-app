#!/usr/bin/env node
// Regenerates DOC_INDEX.md — the bounded entry point into this repo's documentation.
//
// Why this is generated and not hand-written: a hand-written index is prose, and prose about
// file structure rots on the next commit. Run `npm run docs:index` after moving or renaming a
// section and the map is true again. Never edit DOC_INDEX.md by hand.

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();

/** Files whose ## / ### headings become the section map. */
const MAPPED = ["APP_MANIFEST.md", "docs/reference/ARCHITECTURE_QUICKREF.md"];

/** Files listed by name + purpose only — too small or too volatile to map by heading. */
const LISTED = [
  ["CLAUDE.md", "The rules. Read this in full — it is the only doc that is not optional."],
  ["HANDOFF.md", "Onboarding: repo paths, Supabase/Vercel connector discovery, workflow rules."],
  ["AGENTS.md", "Next.js 16 is not the Next.js in your training data. Read before any Next API."],
  ["MEMORY.md", "Current state only: what is in flight, what is open, migration → prod stamps."],
  ["README.md", "Public-facing project readme."],
  ["PRODUCT.md", "What the product is for, in the user's language."],
  ["MATCHMAKING.md", "Standalone narrative of the matchmaking engine."],
  ["src/types/database.ts", "SOURCE OF TRUTH for schema. Read whole. Row types are `type`, never `interface`."],
];

const bytes = (p) => (existsSync(join(ROOT, p)) ? statSync(join(ROOT, p)).size : 0);
const kb = (n) => (n >= 1024 ? `${Math.round(n / 1024)} KB` : `${n} B`);

function headings(relPath) {
  const lines = readFileSync(join(ROOT, relPath), "utf8").split("\n");
  const found = [];
  lines.forEach((line, i) => {
    const m = /^(#{2,3})\s+(.*)$/.exec(line);
    if (m) found.push({ depth: m[1].length, title: m[2].trim(), start: i + 1 });
  });
  return found.map((h, i) => ({
    ...h,
    end: i + 1 < found.length ? found[i + 1].start - 1 : lines.length,
  }));
}

const out = [];
out.push("# DOC_INDEX.md — where to look, and how much of it to read");
out.push("");
out.push("<!-- GENERATED by scripts/gen-doc-index.mjs. Run `npm run docs:index`. Do not edit by hand. -->");
out.push("");
out.push(
  "This repo's documentation is larger than any context window. Reading it whole is not thorough,",
);
out.push(
  "it is a truncation you will not be told about. **Budget ~25k tokens for orientation:** read",
);
out.push("`CLAUDE.md` in full, read `src/types/database.ts` in full, then use the tables below to open");
out.push("only the sections your task touches. Use `sed -n 'START,ENDp' FILE` — the line ranges are exact.");
out.push("");
out.push("After a context compaction, do **not** re-read any of this.");
out.push("");
out.push("---");
out.push("");
out.push("## Read in full");
out.push("");
out.push("| File | Size | Why |");
out.push("|---|---|---|");
for (const [p, why] of LISTED) out.push(`| \`${p}\` | ${kb(bytes(p))} | ${why} |`);
out.push("");

for (const f of MAPPED) {
  if (!existsSync(join(ROOT, f))) continue;
  out.push("---");
  out.push("");
  out.push(`## \`${f}\` — ${kb(bytes(f))}`);
  out.push("");
  out.push("| Section | Lines | Read with |");
  out.push("|---|---|---|");
  for (const h of headings(f)) {
    const indent = h.depth === 3 ? "&nbsp;&nbsp;&nbsp;&nbsp;" : "**";
    const close = h.depth === 3 ? "" : "**";
    const title = h.title.replace(/\|/g, "\\|");
    out.push(
      `| ${indent}${title}${close} | ${h.start}–${h.end} | \`sed -n '${h.start},${h.end}p' ${f}\` |`,
    );
  }
  out.push("");
}

function listDir(dir, heading, blurb) {
  const abs = join(ROOT, dir);
  if (!existsSync(abs)) return;
  const files = readdirSync(abs).filter((f) => f.endsWith(".md")).sort();
  if (!files.length) return;
  out.push("---");
  out.push("");
  out.push(`## ${heading}`);
  out.push("");
  out.push(blurb);
  out.push("");
  out.push("| File | Size |");
  out.push("|---|---|");
  for (const f of files) out.push(`| \`${dir}/${f}\` | ${kb(bytes(join(dir, f)))} |`);
  out.push("");
}

listDir(
  "docs/incidents",
  "`docs/incidents/` — dated write-ups",
  "One file per incident: how a specific bug was found and fixed on a specific day. **Historical.**\n" +
    "The behaviour described may since have been superseded — `src/` is the authority. Open one only\n" +
    "when you need the reasoning behind a past decision.",
);
listDir(
  "docs/archive",
  "`docs/archive/` — retired plans and closed history",
  "Plans for features that already shipped, audits that are fully dispositioned, and the closed\n" +
    "narrative history split out of `MEMORY.md`. **Nothing here is current.** Search it (`grep -rn`),\n" +
    "never read a file end-to-end. A plan that survives its feature is worse than no plan: the next\n" +
    "reader treats it as a gap to close and reintroduces the design that was deliberately rejected.",
);

out.push("---");
out.push("");
out.push("## The rule this index exists to enforce");
out.push("");
out.push("A document is not free to keep. Every line in `APP_MANIFEST.md` and `MEMORY.md` is read by");
out.push("every session, forever, and paid for in context that is then not available for the code. When");
out.push("an item closes, move it out. When a plan ships, archive it. When a claim is dated, it is an");
out.push("incident write-up and belongs in `docs/incidents/`.");
out.push("");

writeFileSync(join(ROOT, "DOC_INDEX.md"), out.join("\n"));
console.log(`DOC_INDEX.md written (${statSync(join(ROOT, "DOC_INDEX.md")).size} bytes)`);
